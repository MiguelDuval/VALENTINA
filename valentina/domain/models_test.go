func TestOpportunityValidateBeforeEnsureID(t *testing.T) {
	o := &Opportunity{
		Title:              "Test",
		Summary:            "Test summary",
		OpportunityType:    "test",
		Status:             OpportunityStatusCandidate,
		DemandEvidenceType: DemandEvidenceUnknown,
		SourceEvidenceIDs:  []string{"ev1"},
	}
	err := o.Validate()
	if err == nil {
		t.Fatal("Validate should fail when OpportunityID is empty")
	}
	o.EnsureID()
	err = o.Validate()
	if err != nil {
		t.Fatalf("Validate should pass after EnsureID: %v", err)
	}
}

