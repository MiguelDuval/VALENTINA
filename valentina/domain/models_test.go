func TestLocationSingleDefinition(t *testing.T) {
	var loc Location
	loc.Municipality = strPtr("Valencia")
	loc.CountryCode = strPtr("ES")
	if loc.Municipality == nil || *loc.Municipality != "Valencia" {
		t.Fatal("Location struct fields should work")
	}
}

func TestOpportunityValueNilSafety(t *testing.T) {
	o := &Opportunity{
		OpportunityID:      "test-id",
		Title:              "Test",
		Summary:            "Test",
		Status:             OpportunityStatusCandidate,
		DemandEvidenceType: DemandEvidenceUnknown,
		SourceEvidenceIDs:  []string{"ev1"},
	}
	if o.Value != nil {
		t.Fatal("Value should be nil when not set")
	}
	o.Value = &OpportunityValue{Amount: float64Ptr(1000)}
	if o.Value.Amount == nil || *o.Value.Amount != 1000 {
		t.Fatal("OpportunityValue should hold amount")
	}
}

