func TestValidateDuplicateCandidate(t *testing.T) {
	existing := []*Opportunity{
		{OpportunityID: "existing-1", Title: "Test"},
	}
	newOpp := &Opportunity{OpportunityID: "new-1", Title: "Different"}
	err := ValidateDuplicateCandidate(newOpp, existing)
	if err != nil {
		t.Fatalf("Should not flag different opportunities as duplicates: %v", err)
	}
}

