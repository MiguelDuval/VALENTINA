func TestOpportunityEnsureID(t *testing.T) {
	o := &Opportunity{Title: "Test"}
	o.EnsureID()
	if o.OpportunityID == "" {
		t.Fatal("OpportunityID should be generated by EnsureID")
	}
	existing := o.OpportunityID
	o.EnsureID()
	if o.OpportunityID != existing {
		t.Fatal("EnsureID should not overwrite existing ID")
	}
}

